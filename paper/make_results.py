"""Turn real demo/pytest output into LaTeX macros (no hand-typed numbers)."""
import json, os, re
D = os.path.dirname(os.path.abspath(__file__))
r = json.load(open(os.path.join(D, "results.json")))
txt = open(os.path.join(D, "pytest_output.txt")).read()
passed = int(re.search(r"(\d+) passed", txt).group(1))
failed = int(m.group(1)) if (m := re.search(r"(\d+) failed", txt)) else 0
secs = re.search(r"passed in ([\d.]+)s", txt).group(1)
cases = [(int(a), int(b)) for a, b in re.findall(r"(\d+) passing, (\d+) failing", txt)]
plat = re.search(r"platform (.*?) -- Python ([\d.]+), pytest-([\d.]+)", txt)
hyp = re.search(r"hypothesis-([\d.]+)", txt).group(1)
names = re.findall(r"tests/(test_\w+)\.py::(\w+) PASSED", txt)
m = {}
def fmt(x):
    if x == 0: return "0"
    s = f"{x:.2e}"; a, e = s.split("e"); e = int(e)
    return a if e == 0 else f"{a}\\times10^{{{e}}}"
def put(k, v): m[k] = v
put("Npassed", passed); put("Nfailed", failed); put("Ntime", secs)
put("Nprop", len(cases)); put("Ncases", sum(a for a, _ in cases)); put("Ncasefail", sum(b for _, b in cases))
put("PyVer", plat.group(2)); put("PytestVer", plat.group(3)); put("HypVer", hyp)
put("ExPsi", f"{r['psi']:.3f}"); put("ExDaily", f"{r['daily']:.2f}"); put("ExBlend", f"{r['blended_daily']:.2f}")
for k, v in r["equations"].items(): put("Eq" + k.capitalize(), f"{v:.2f}")
put("ExRec", r["recommendation"].replace(":", ":"))
put("DGzero", f"{r['degroot_spreads_first'][0]:.3f}"); put("DGone", f"{r['degroot_spreads_first'][1]:.3f}")
put("DGthirty", fmt(r['degroot_spread_30'])); put("DGsixty", fmt(r['degroot_spread_60']))
put("DGlazythirty", fmt(r['degroot_lazy_spread_30']))
put("DGsteps", r["steps_to_1e-6"]); put("LamTwo", f"{r['second_eig_modulus']:.4f}")
put("LamTwoLazy", f"{r['lazy_second_eig_modulus']:.4f}")
put("WfourMin", f"{r['W4_min']:.4f}"); put("DobW", f"{r['dobrushin_W']:.4f}"); put("DobWfour", f"{r['dobrushin_W4']:.4f}")
put("QBound", f"{1-5*r['W4_min']:.4f}")
put("ConstRes", fmt(max(r["constant_residuals"].values())))
put("FJzero", f"{r['fj_residual_0']:.3f}")
for k in ("10", "20", "40"):
    s = f"{r['fj_residual_'+k]:.2e}"; a, e = s.split("e-")
    put("FJ" + {"10": "ten", "20": "twenty", "40": "forty"}[k], f"{a}\\times10^{{-{int(e)}}}")
for row in r["random_graphs"]:
    n = {4: "four", 8: "eight", 16: "sixteen"}[row["n"]]
    put("RGmean" + n, fmt(row["mean_ratio"])); put("RGmax" + n, fmt(row["max_ratio"]))
    put("RGbound" + n, f"{row['mean_bound']:.3f}"); put("RGviol" + n, row["violations"])
    put("RGmed" + n, f"{row['median_steps']:.0f}"); put("RGmaxsteps" + n, row["max_steps"])
with open(os.path.join(D, "results.tex"), "w") as f:
    f.write("% generated by make_results.py from pytest_output.txt and results.json\n")
    for k, v in m.items():
        f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    # per-unit table
    f.write("\\newcommand{\\UnitRows}{%\n")
    for u in ("Mistfawn", "Tidelyn", "Lumowl", "Brakkor", "Hivewright"):
        f.write(f"{u} & {r['needs'][u]:.3f} & {r['activations'][u]:.3f} & {r['harmonized'][u]:.3f} & "
                f"{r['consensus'][u]:.3f} & {r['allocation'][u]:.3f}\\\\\n")
    f.write("}\n")
    f.write("\\newcommand{\\TestRows}{%\n")
    per = dict(re.findall(r"tests/test_\w+\.py::(\w+):\n.*?(\d+) passing", txt, re.S))
    for mod, name in names:
        n_ = per.get(name, "--")
        mod = mod.replace('_', chr(92)+'_')
        f.write(f"\\texttt{{{mod}}} & \\texttt{{{name.replace('_', chr(92)+'_')}}} & {n_} & pass\\\\\n")
    f.write("}\n")
print(open(os.path.join(D, "results.tex")).read()[:3000])
